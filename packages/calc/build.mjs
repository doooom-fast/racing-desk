// Bundles the engines + local model for the desk window: a classic script defining window.RaceCorCalc.
import { build } from 'esbuild'
import { fileURLToPath } from 'node:url'

const here = (p) => fileURLToPath(new URL(p, import.meta.url))

await build({
  entryPoints: [here('./src/index.ts')],
  outfile: here('../../apps/overlay/modules/desk/calc.bundle.js'),
  bundle: true,
  format: 'iife',
  globalName: 'RaceCorCalc',
  platform: 'browser',
  target: 'chrome130',
  legalComments: 'none',
  banner: { js: '// Generated by packages/calc (npm run build -w @prodrive/calc). Do not edit.' },
  logLevel: 'info',
})
