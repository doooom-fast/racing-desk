using System.Collections.Generic;
using Newtonsoft.Json;

namespace RacingDesk.Plugin
{
    public class Settings
    {
        /// <summary>
        /// Where iRacing published this season's schedule PDF. The only thing The Racing Desk fetches, and never at
        /// race time. A PDF dropped into %LOCALAPPDATA%\RacingDesk\schedule by hand is used just the same.
        /// </summary>
        public string ScheduleUrl { get; set; } = "https://us.v-cdn.net/6034148/uploads/597LPPDHT83M/2026s4.pdf";

        /// <summary>
        /// Where the app's host serves its store on this machine. The SimHub plugin asks it for the track map's
        /// outlines (the host runs beside SimHub on :18889 while SimHub holds :8889). Loopback only, and the address
        /// the host answers on (<c>RacingDeskRuntime.HttpPrefixGroups</c> names it). It is the app's, not a
        /// setting: never saved, so that SimHub does not keep an old address after the app moves.
        /// </summary>
        [JsonIgnore]
        public string HostUrl { get; set; } = "http://127.0.0.1:18889";

        /// <summary>How long (seconds) each prompt stays on screen before auto-clearing.</summary>
        public double PromptDisplaySeconds { get; set; } = 15.0;

        /// <summary>
        /// Categories to include. Empty list = all categories enabled.
        /// Valid values: hardware, game_feel, car_response, racing_experience
        /// </summary>
        public List<string> EnabledCategories { get; set; } = new List<string>();

        /// <summary>Path to commentary_topics.json. Defaults to racingdesk-data subfolder next to DLL.</summary>
        public string TopicsFilePath { get; set; } = "";

        /// <summary>Whether to show the topic title above the prompt text.</summary>
        public bool ShowTopicTitle { get; set; } = true;

        /// <summary>
        /// When true, displays a concise exposition of the event and its telemetry value
        /// instead of the full commentary prompt. Designed for on-air readability.
        /// </summary>
        public bool EventOnlyMode { get; set; } = false;

        /// <summary>
        /// When true, the engine runs a self-contained demo sequence that cycles through
        /// all event types and severity levels as if a race were in progress.
        /// Maximum 30 seconds between events. No game session required.
        /// </summary>
        public bool DemoMode { get; set; } = false;

        /// <summary>
        /// The driver's first name, used for 3rd-person commentary.
        /// Auto-populated from iRacing when available; falls back to "the driver" if empty.
        /// </summary>
        public string DriverFirstName { get; set; } = "";

        /// <summary>
        /// The driver's last name, used for 3rd-person commentary.
        /// Auto-populated from iRacing when available; falls back to "the driver" if empty.
        /// </summary>
        public string DriverLastName { get; set; } = "";


        // ── Incident Coach ────────────────────────────────────────────────

        /// <summary>Whether the Incident Coach system is enabled.</summary>
        public bool IncidentCoachEnabled { get; set; } = false;

        /// <summary>Whether voice coaching prompts should be generated by Incident Coach.</summary>
        public bool IncidentCoachVoiceEnabled { get; set; } = true;

        /// <summary>Rage score threshold (40–90) for automatic cool-down activation.</summary>
        public int IncidentCoachCooldownThreshold { get; set; } = 70;

        /// <summary>Alert sensitivity multiplier. Low=0.7, Medium=1.0, High=1.3.</summary>
        public double IncidentCoachAlertSensitivity { get; set; } = 1.0;
    }
}
