// Bundles the livery manager's UI for the desk window: a classic script defining window.RacingDeskPaints (mount,
// unmount) and its stylesheet, into apps/overlay/modules/desk/ — the same shape as packages/calc/build.mjs. Run by
// the overlay's prestart/predev, the root build and the desk tests; the output is generated, not committed.
import { build } from 'esbuild'
import { fileURLToPath } from 'node:url'

const here = (p) => fileURLToPath(new URL(p, import.meta.url))

await build({
  entryPoints: [here('./src/island.tsx')],
  outfile: here('../overlay/modules/desk/paints.bundle.js'),
  bundle: true,
  minify: true,
  format: 'iife',
  globalName: 'RacingDeskPaints',
  platform: 'browser',
  target: 'chrome130',
  jsx: 'automatic',
  define: { 'process.env.NODE_ENV': '"production"' },
  legalComments: 'none',
  banner: {
    js: '// Generated by apps/paints/build-island.mjs. Do not edit.',
    css: '/* Generated by apps/paints/build-island.mjs. Do not edit. */',
  },
  logLevel: 'info',
})
